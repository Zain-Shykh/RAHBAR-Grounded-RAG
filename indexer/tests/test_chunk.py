def test_isolated_line_rule():
    assert _heading("Fee Refund Policy", True, True) == "Fee Refund Policy"
    assert _heading("Fee Refund Policy", False, True) is None          # glued to the text above
    assert _heading("Fee Refund Policy", True, False) is None          # nothing below
    assert _heading("Note: days shall be counted.", True, True) is None
    assert _heading("Payment steps:", True, True) is None
    assert _heading("This heading has far too many words to be a real heading line", True, True) is None
    assert _heading("lowercase start", True, True) is None


def test_section_text_and_truncation():
    long = "4.3 " + " ".join(f"Word{i}" for i in range(25))
    cs = chunk(doc(long + "\nmore"), 400, 50)
    assert len(cs[0].section) <= 80 and cs[0].section.startswith("4.3 Word0")
    assert not cs[0].section.endswith(" ") and "Word3" in cs[0].section
    cs = chunk(doc("1.1   Spaced \t  out   heading\nbody"), 400, 50)
    assert cs[0].section == "1.1 Spaced out heading"


