"""Chunker tests (phase 6 spec section 7). Synthetic documents only: no corpus, no network."""

import re

import pytest
from pipeline.chunk import _heading, chunk
from pipeline.models import Document, Page


def doc(*pages: str, source: str = "rules-2026.pdf", version: str = "2026-06",
        superseded: bool = False) -> Document:
    return Document(source, version, superseded, [Page(source, i + 1, t) for i, t in enumerate(pages)])


def words(text: str) -> int:
    return len(text.split())


def para(n: int, tag: str = "w") -> str:
    """n words, as sentences of 10 words."""
    out = [f"{tag}{i}" + ("." if i % 10 == 9 else "") for i in range(n)]
    return " ".join(out)


# ---- AC-1 metadata and ids --------------------------------------------------------------

def test_metadata_and_ids():
    d = doc("1.1 Alpha rule text here.\n\n1.2 Beta rule text here.", superseded=True, version="2023-08")
    cs = chunk(d, 400, 50)
    assert len(cs) == 2
    for c in cs:
        assert set(c.metadata()) == {"source", "section", "page", "doc_version", "superseded"}
        assert c.source == "rules-2026.pdf" and c.doc_version == "2023-08" and c.superseded is True
        assert isinstance(c.page, int) and c.page >= 1 and c.section and c.text
        assert re.fullmatch(r"[a-z0-9._-]+-p\d{3}-c\d{3}", c.id)
    assert [c.id for c in cs] == ["rules-2026-p001-c001", "rules-2026-p001-c002"]


def test_ids_unique_and_stable_across_runs():
    d = doc(*[f"{i}.1 Clause {i}\n" + para(300, f"t{i}_") for i in range(1, 6)])
    a, b = chunk(d, 120, 20), chunk(d, 120, 20)
    assert [(c.id, c.text) for c in a] == [(c.id, c.text) for c in b]
    assert len({c.id for c in a}) == len(a)


def test_id_page_is_page_of_first_new_text():
    d = doc("1.1 Intro\n" + para(30), para(30, "next"))
    cs = chunk(d, 40, 10)
    assert cs[0].page == 1
    assert any(c.page == 2 for c in cs)
    for c in cs:
        assert f"-p{c.page:03d}-" in c.id


# ---- AC-2 size cap and one document -----------------------------------------------------

def test_size_cap_and_single_source():
    d = doc("1.1 Big\n" + para(1000), "\n\n".join(para(70, f"p{i}_") for i in range(20)))
    for size, overlap in [(50, 10), (100, 0), (400, 50), (30, 29)]:
        cs = chunk(d, size, overlap)
        assert cs and all(words(c.text) <= size for c in cs), (size, overlap)
        assert {c.source for c in cs} == {d.source}


def test_single_long_row_allowed():
    row = "Name | " + " | ".join(f"cell{i}" for i in range(60))
    cs = chunk(doc("1.1 Table\n\n" + row), 20, 5)
    assert any(c.text.count(" | ") >= 60 for c in cs)  # kept whole although > size


# ---- AC-3 overlap -----------------------------------------------------------------------

def test_overlap_within_section():
    cs = chunk(doc("1.1 Long clause\n" + para(300)), 100, 20)
    assert len(cs) >= 3
    for prev, nxt in zip(cs, cs[1:], strict=False):
        assert nxt.text.split()[:20] == prev.text.split()[-20:]


def test_no_overlap_across_sections():
    cs = chunk(doc("1.1 First\n" + para(30, "a") + "\n\n1.2 Second\n" + para(30, "b")), 100, 20)
    assert len(cs) == 2
    assert cs[1].text.startswith("1.2 Second")
    assert "a0" not in cs[1].text.split() and cs[1].section.startswith("1.2")


def test_no_overlap_after_table_row():
    rows = "\n".join(f"item{i} | Rs. {i}00" for i in range(25))
    cs = chunk(doc("Fees\n" + rows), 30, 10)
    assert len(cs) >= 2
    for c in cs:
        for line in c.text.split("\n"):
            assert line == "Fees" or re.fullmatch(r"item\d+ \| Rs\. \d+00", line), line


# ---- AC-4 numbered sub-section in one chunk ---------------------------------------------

def test_numbered_subsection_in_one_chunk():
    text = ("XII - POLICY ON GENERATIVE AI BASED TOOLS\n"
            "4. Acceptable Uses of Generative AI Tools\n" + para(90, "ok") + "\n"
            "5. Unacceptable Uses of Generative AI Tools\n"
            "1) Students generating an entire assignment submission and passing it off.\n"
            "2) Submitting content generated by tools without citation.\n"
            "3) Using tools which paraphrase text to pass off the work of another person.\n" + para(150, "bad"))
    cs = chunk(doc(text, source="student-handbook-jun-2026.pdf"), 400, 50)
    five = [c for c in cs if c.section.startswith("5. Unacceptable")]
    assert len(five) == 1 and "entire assignment" in five[0].text and "bad149" in five[0].text.replace(".", "")
    assert five[0].section == "5. Unacceptable Uses of Generative AI Tools"


